// Vendors connector brand marks into `src/components/ConnectorLogo/logos.ts`.
//
// The marks themselves live with the product that owns them (the Insightis app
// ships one SVG per connector); the design system only carries the subset the
// kit needs, inlined as data URIs so a rendered page — Storybook, the Claude
// Design canvas, a consumer's build — never has to fetch anything.
//
//   node scripts/gen-connector-logos.mjs --src <dir-of-svgs> [--only a,b,c]
//
// Re-run it with a longer `--only`, or without it, to widen the pack.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(`--${name}`);
  return i === -1 ? undefined : args[i + 1];
};

const src = flag('src');
if (!src) {
  console.error(
    'usage: node scripts/gen-connector-logos.mjs --src <dir> [--only a,b,c]'
  );
  process.exit(1);
}
const only = flag('only')
  ?.split(',')
  .map((s) => s.trim())
  .filter(Boolean);

const OUT = 'src/components/ConnectorLogo/logos.ts';

const slugs = (
  only ??
  readdirSync(src)
    .filter((f) => f.endsWith('.svg'))
    .map((f) => basename(f, '.svg'))
).sort();

const toDataUri = (svg) =>
  `data:image/svg+xml,${encodeURIComponent(
    svg
      .replace(/<\?xml[^>]*\?>/g, '')
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/\s+/g, ' ')
      .trim()
  )}`;

const entries = slugs.map((slug) => {
  const svg = readFileSync(join(src, `${slug}.svg`), 'utf8');
  return `  ${/^[a-z][a-z0-9]*$/.test(slug) ? slug : JSON.stringify(slug)}:\n    '${toDataUri(svg)}',`;
});

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-connector-logos.mjs — do not edit by hand.
// Each mark is the vendor's own SVG, inlined so nothing is fetched at render
// time. Widen the pack by re-running the script against the app's logo folder.

export const CONNECTOR_LOGOS = {
${entries.join('\n')}
} as const;

/** Every mark the design system carries today. */
export type ConnectorSlug = keyof typeof CONNECTOR_LOGOS;
`
);

const bytes = entries.join('').length;
console.log(
  `wrote ${OUT}: ${slugs.length} marks, ${Math.round(bytes / 1024)} KB inlined`
);
