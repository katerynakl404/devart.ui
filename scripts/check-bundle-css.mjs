/**
 * Reports CSS rules the components need but `ds-bundle` does not ship.
 *
 * This is the gap that makes a component look right in Storybook and wrong on a
 * page. Storybook compiles Tailwind from the source files, so every class a
 * component writes gets a rule. `ds-bundle` compiles from
 * `.design-sync/.cache/ds-classlist.txt`, which is an ENUMERATED vocabulary —
 * written out by `gen-classlist.mjs`, not scraped from the components. A class
 * the enumeration missed produces no CSS, and nothing errors: Tailwind only
 * emits what it was asked for.
 *
 * Method: run Tailwind a second time with the BUILT COMPONENTS as its content,
 * then diff the class selectors it emits against the ones in the bundle. The
 * point of doing it this way rather than with a regex is that Tailwind's own
 * extractor decides what counts as a class — so import specifiers, `data-slot`
 * values and `group/name` markers never enter the comparison, and custom
 * variants like `not-last:` are resolved by the same config the bundle uses.
 *
 * The check is one-directional. The class list is deliberately WIDER than what
 * the components use — a design agent composing its own layout needs the
 * vocabulary too — so "in the bundle, unused" is expected and not reported.
 *
 * What it still cannot see: a class assembled at runtime from a variable is not
 * in the compiled text, so no extractor can find it. `.ds-sync/storybook/
 * compare.mjs` is the check that closes that last gap, by rendering both and
 * comparing pixels.
 */
import { execFileSync } from 'node:child_process';
import {
  existsSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const BUNDLE_CSS = join(ROOT, 'ds-bundle/_ds_bundle.css');
const DIST = join(ROOT, 'dist');

if (!existsSync(BUNDLE_CSS) || !existsSync(DIST)) {
  console.error('check-bundle-css: no bundle or no dist — nothing to compare');
  process.exit(0);
}

const work = mkdtempSync(join(tmpdir(), 'ds-css-'));
// The probe config lives inside the repo, not in the temp dir: Tailwind loads it
// with jiti, and a relative `../tailwind-export.config` resolves the same way the
// real build does. It is a sibling of the file it extends, so nothing about the
// preset, the plugins or the custom variants is re-stated here — the two compiles
// differ in exactly one variable, `content`.
const cfg = join(ROOT, '.design-sync/.cache/_probe.config.ts');
try {
  writeFileSync(
    cfg,
    "import base from '../tailwind-export.config';\n\n" +
      '/* Generated by scripts/check-bundle-css.mjs. Deleted when it finishes. */\n' +
      '/* The glob is relative to the CWD Tailwind runs in (the package root),\n' +
      '   not to this file — resolving it against the file silently matches\n' +
      '   nothing and the check then passes without having looked at anything. */\n' +
      "export default { ...base, content: ['dist/**/*.js'] };\n"
  );

  const out = join(work, 'probe.css');
  // `corepack` is a .cmd on Windows and cannot be spawned without a shell, so
  // call Tailwind's own CLI entry point directly.
  execFileSync(
    process.execPath,
    [
      join(ROOT, 'node_modules/tailwindcss/lib/cli.js'),
      '-c',
      cfg,
      '-i',
      join(ROOT, '.design-sync/tailwind-export.css'),
      '-o',
      out,
      '--minify',
    ],
    { cwd: ROOT, stdio: ['ignore', 'ignore', 'pipe'] }
  );

  /** Class selectors a stylesheet defines, un-escaped back to source form. */
  const selectors = (css) => {
    const s = new Set();
    for (const m of css.matchAll(/\.((?:\\.|[^\s.,{>+~:[\]()])+)/g)) {
      // A decimal inside a declaration — `translateY(-.125rem)` — looks exactly
      // like the start of a class. An unescaped class name cannot begin with a
      // digit, so that one rule separates the two.
      if (/^\d/.test(m[1])) continue;
      s.add(m[1].replace(/\\(.)/g, '$1'));
    }
    return s;
  };

  const needed = selectors(readFileSync(out, 'utf8'));
  const shipped = selectors(readFileSync(BUNDLE_CSS, 'utf8'));
  const missing = [...needed].filter((c) => !shipped.has(c)).sort();

  // Reported as if/else rather than an early exit: `process.exit()` skips
  // `finally`, which would leave the probe config sitting in the repo after
  // every successful run.
  if (!missing.length) {
    console.error(
      `check-bundle-css: ok — every rule the components need is in the bundle ` +
        `(${needed.size} checked against ${shipped.size} shipped)`
    );
  } else {
    console.error(
      `\ncheck-bundle-css: ${missing.length} rule(s) the components need are MISSING from ` +
        `ds-bundle/_ds_bundle.css.\nThese render in Storybook and silently do nothing on a page. ` +
        `Add them to .design-sync/gen-classlist.mjs and rebuild.\n`
    );
    for (const c of missing.slice(0, 60)) console.error(`  ${c}`);
    if (missing.length > 60)
      console.error(`  … and ${missing.length - 60} more`);
    process.exitCode = 1;
  }
} finally {
  rmSync(work, { recursive: true, force: true });
  rmSync(cfg, { force: true });
}
