/**
 * Every cva recipe in the package, rendered to the class string it produces.
 *
 * Storybook only shows the variants someone remembered to add a story for, so a
 * base-string edit can silently re-style variants nobody is looking at. This
 * walks the config each recipe carries (see `lib/cva.ts`), so coverage is
 * complete by construction and the review artefact is a readable diff: one line
 * per variant value, which makes "this touched one variant" and "this touched
 * all thirty" impossible to confuse.
 */
import { expect, it } from 'vitest';
import type { CvaConfig } from '../lib/cva';

type Recipe = ((props?: Record<string, unknown>) => string) & {
  config?: CvaConfig;
};

const isRecipe = (value: unknown): value is Recipe =>
  typeof value === 'function' && 'config' in value;

const modules = import.meta.glob<Record<string, unknown>>(
  [
    '../components/**/*.tsx',
    '!../components/**/*.stories.tsx',
    '!../components/**/*.test.tsx',
  ],
  { eager: true }
);

/** `{ variant: 'primary', size: 'md' }` → `variant=primary, size=md`. */
const describeProps = (props: Record<string, unknown>) =>
  Object.entries(props)
    .map(([key, value]) => `${key}=${String(value)}`)
    .join(', ');

const renderRecipe = (recipe: Recipe): string[] => {
  const lines: string[] = [];
  const config = recipe.config;

  if (config?.defaultVariants && Object.keys(config.defaultVariants).length) {
    lines.push(`defaultVariants: ${describeProps(config.defaultVariants)}`, '');
  }

  lines.push('(defaults)', `  ${recipe()}`);

  for (const [axis, values] of Object.entries(config?.variants ?? {})) {
    for (const value of Object.keys(values)) {
      lines.push(`${axis}=${value}`, `  ${recipe({ [axis]: value })}`);
    }
  }

  config?.compoundVariants?.forEach((compound, index) => {
    const { class: _c, className: _cn, ...props } = compound;
    lines.push(
      `compound[${index}] ${describeProps(props)}`,
      `  ${recipe(props)}`
    );
  });

  return lines;
};

it('every cva recipe matches its snapshot', async () => {
  const sections: string[] = [
    '# Recipe snapshots',
    '',
    'Generated by `src/__tests__/recipes.test.ts`. Never edit this file by hand —',
    'run `pnpm test:unit:update` after an intentional recipe change. Editing it',
    'to match broken output turns the gate green over a broken component.',
    '',
    'One line per variant value, holding every other axis at its default. A diff',
    'confined to one line is a one-variant change; a diff across every line of a',
    'component means a shared base string moved.',
    '',
  ];

  // A recipe re-exported from a barrel is the same object, so identity dedupes
  // it; the sorted walk means the file that declares it wins the heading.
  const seen = new Set<Recipe>();

  for (const path of Object.keys(modules).sort()) {
    const module = modules[path];
    if (!module) continue;

    for (const [exportName, value] of Object.entries(module)) {
      if (!isRecipe(value) || seen.has(value)) continue;
      seen.add(value);
      sections.push(
        `## ${path.replace('../', '')} — ${exportName}`,
        '',
        ...renderRecipe(value),
        ''
      );
    }
  }

  await expect(sections.join('\n')).toMatchFileSnapshot(
    './__snapshots__/recipes.md'
  );
});
